import { AI_SYSTEM_BOUNDARY } from './content.js';

/**
 * Server-side AI integration for OpenAI-compatible chat completion APIs.
 * Credentials stay on the server. When no key is configured every AI route
 * reports an honest unavailable state; nothing is simulated.
 */

export function aiConfig() {
  const apiKey = process.env.AI_API_KEY || process.env.OPENAI_API_KEY || '';
  const baseUrl = (process.env.AI_BASE_URL || 'https://api.openai.com/v1').replace(/\/+$/, '');
  const model = process.env.AI_MODEL || 'gpt-4o-mini';
  return {
    configured: Boolean(apiKey),
    apiKey,
    baseUrl,
    model,
    provider: new URL(baseUrl).host,
    timeoutMs: Number(process.env.AI_TIMEOUT_MS ?? 25000)
  };
}

export function aiStatus() {
  const config = aiConfig();
  return {
    configured: config.configured,
    model: config.model,
    provider: config.provider,
    // Never expose the key; only whether one exists and where it is read from.
    keySource: process.env.AI_API_KEY ? 'AI_API_KEY' : process.env.OPENAI_API_KEY ? 'OPENAI_API_KEY' : null,
    note: config.configured
      ? 'AI responses are generated by the configured model using only the STRANDPATH context sent from the server.'
      : 'No AI key is configured. Assessment scores, explanations and improvement programmes still work; coach and support chat are disabled.'
  };
}

const COACH_INSTRUCTIONS = `${AI_SYSTEM_BOUNDARY}

You are the STRANDPATH Virtual Coach. Your job is academic guidance and student development:
explaining assessment results, comparing strands, discussing college programmes and careers,
and suggesting learning activities. Keep answers under 220 words unless the student asks for detail.
Use the student context below. Refer to actual scores only as they appear in the context; never round
or invent numbers. If the student asks something outside the context (specific school policies,
admission cut-offs, scholarship deadlines) say that you cannot verify it and suggest asking the
school guidance office.`;

const SUPPORT_INSTRUCTIONS = `${AI_SYSTEM_BOUNDARY}

You are the STRANDPATH Support Agent. You only help with technical support, accounts, navigation
and troubleshooting inside STRANDPATH. You do not give academic guidance about strands; for that,
tell the student the Virtual Coach is the right place. Keep answers short and step-by-step.
If the problem needs a human (account recovery, missing records, suspected data error), tell the
student to submit a support request from the Support page and summarise what to include.
Never ask for a password or any secret.`;

export function buildMessages({ agent, question, context, history = [] }) {
  const instructions = agent === 'support' ? SUPPORT_INSTRUCTIONS : COACH_INSTRUCTIONS;
  const messages = [{ role: 'system', content: instructions }];
  if (context) {
    messages.push({
      role: 'system',
      content: `STRANDPATH CONTEXT (authorised, read-only):\n${context}`
    });
  }
  for (const message of history.slice(-10)) {
    if (message.role === 'user' || message.role === 'assistant') {
      messages.push({ role: message.role, content: message.content });
    }
  }
  messages.push({ role: 'user', content: question });
  return messages;
}

export async function complete(messages) {
  const config = aiConfig();
  if (!config.configured) {
    const error = new Error('AI is not configured on this server.');
    error.status = 503;
    error.code = 'AI_UNAVAILABLE';
    error.expose = true;
    throw error;
  }
  const controller = new AbortController();
  const timer = setTimeout(() => controller.abort(), config.timeoutMs);
  try {
    const response = await fetch(`${config.baseUrl}/chat/completions`, {
      method: 'POST',
      headers: {
        'Content-Type': 'application/json',
        Authorization: `Bearer ${config.apiKey}`
      },
      body: JSON.stringify({
        model: config.model,
        messages,
        temperature: 0.4,
        max_tokens: 700
      }),
      signal: controller.signal
    });
    if (!response.ok) {
      const detail = await response.text().catch(() => '');
      console.error('[ai] provider error', response.status, detail.slice(0, 400));
      const error = new Error(
        response.status === 401 || response.status === 403
          ? 'The configured AI key was rejected by the provider.'
          : 'The AI provider could not complete this request.'
      );
      error.status = 502;
      error.code = 'AI_PROVIDER_ERROR';
      error.expose = true;
      throw error;
    }
    const data = await response.json();
    const content = data?.choices?.[0]?.message?.content;
    if (!content || typeof content !== 'string') {
      const error = new Error('The AI provider returned an empty response.');
      error.status = 502;
      error.code = 'AI_EMPTY_RESPONSE';
      error.expose = true;
      throw error;
    }
    return { content: content.trim(), model: data.model ?? config.model };
  } catch (err) {
    if (err.name === 'AbortError') {
      const error = new Error('The AI request timed out.');
      error.status = 504;
      error.code = 'AI_TIMEOUT';
      error.expose = true;
      throw error;
    }
    throw err;
  } finally {
    clearTimeout(timer);
  }
}
